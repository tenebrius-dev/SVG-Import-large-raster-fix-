import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(await readFile(path.join(root, "icons", "manifest.generated.json"), "utf8"));
const args = process.argv.slice(2);

function argument(name) {
  const index = args.indexOf(name);
  return index === -1 ? null : args[index + 1];
}

const canonical = new Map();
for (const icon of manifest.icons) {
  if (!canonical.has(icon.canonicalName)) canonical.set(icon.canonicalName, icon);
}

if (args.includes("--list")) {
  for (const name of [...canonical.keys()].sort()) console.log(name);
  process.exit(0);
}

const requested = argument("--icons");
const names = args.includes("--all")
  ? [...canonical.keys()].sort()
  : (requested || "").split(",").map(value => value.trim()).filter(Boolean);

if (!names.length) {
  console.error("Укажите --icons icon.16.close,icon.24.check или используйте --all.");
  process.exit(1);
}

const unknown = names.filter(name => !canonical.has(name));
if (unknown.length) {
  console.error("Неизвестные или недоступные иконки: " + unknown.join(", "));
  process.exit(1);
}

const uniqueNames = [...new Set(names)];
const entries = [];
for (const name of uniqueNames) {
  const icon = canonical.get(name);
  const svg = (await readFile(path.join(root, "icons", icon.file), "utf8")).trim();
  entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`);
}

const output = [
  "// Generated by ui3-plugin-design-system/scripts/build-icon-module.mjs.",
  "// Do not edit by hand; regenerate from icons/manifest.generated.json.",
  "export const ui3Icons = {",
  ...entries,
  "} as const;",
  "",
  "export type Ui3IconName = keyof typeof ui3Icons;",
  "",
  "export function getUi3IconSvg(name: Ui3IconName): string {",
  "  return ui3Icons[name];",
  "}",
  "",
].join("\n");

const outputPath = path.resolve(process.cwd(), argument("--out") || "src/ui3-icons.selected.ts");
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");
console.log(`Wrote ${outputPath} (${uniqueNames.length} icons).`);
